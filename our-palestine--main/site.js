const translationAttributes = [
    ['i18n', 'textContent'],
    ['i18nAriaLabel', 'aria-label'],
    ['i18nTitle', 'title']
];

function readSiteOverrides() {
    const savedOverrides = localStorage.getItem('ourPalestineOverrides');
    if (!savedOverrides) {
        return {};
    }

    const overrides = JSON.parse(savedOverrides);
    if (!overrides || typeof overrides !== 'object' || Array.isArray(overrides)) {
        throw new Error('Saved site text overrides have an invalid format.');
    }
    return overrides;
}

function initializeSite() {
    const yearElement = document.getElementById('year');
    const langToggle = document.getElementById('lang-toggle');
    const menuToggle = document.getElementById('menu-toggle');
    const menu = document.getElementById('menu');
    if (menu && !menu.querySelector('[href$="chat.html"]')) {
        const chatItem = document.createElement('li');
        const chatLink = document.createElement('a');
        chatLink.className = 'nav-link';
        chatLink.href = 'chat.html';
        chatLink.innerHTML = '<svg class="nav-icon" viewBox="0 0 24 24" aria-hidden="true"><path d="M20 11.5a7.5 7.5 0 0 1-7.5 7.5H6l-3 2v-9.5A7.5 7.5 0 0 1 10.5 4h2A7.5 7.5 0 0 1 20 11.5Z"></path></svg><span data-i18n="nav.chat">Chat</span>';
        chatItem.appendChild(chatLink);
        menu.appendChild(chatItem);
    }
    if (menu && !menu.querySelector('[href$="work.html"]')) {
        const workItem = document.createElement('li');
        const workLink = document.createElement('a');
        workLink.className = 'nav-link';
        workLink.href = 'work.html';
        workLink.innerHTML = '<svg class="nav-icon" viewBox="0 0 24 24" aria-hidden="true"><rect x="3" y="7" width="18" height="14" rx="2"></rect><path d="M8 7V5a2 2 0 0 1 2-2h4a2 2 0 0 1 2 2v2m-13 5h18m-11 0v2h4v-2"></path></svg><span data-i18n="nav.work">Work</span>';
        workItem.appendChild(workLink);
        menu.appendChild(workItem);
    }
    const navLinks = document.querySelectorAll('.nav-link');
    const translatedElements = document.querySelectorAll('[data-i18n], [data-i18n-aria-label], [data-i18n-title]');
    let currentLang = new URLSearchParams(window.location.search).get('lang') === 'ar' ? 'ar' : 'en';
    let siteOverrides = {};

    try {
        siteOverrides = readSiteOverrides();
    } catch (error) {
        console.error('Could not read saved site text changes.', error);
    }

    if (yearElement) {
        yearElement.textContent = new Date().getFullYear();
    }

    function setLanguage(lang) {
        currentLang = lang;
        const isArabic = lang === 'ar';

        document.documentElement.lang = lang;
        document.body.dir = isArabic ? 'rtl' : 'ltr';
        langToggle.textContent = isArabic ? 'English' : 'العربية';
        langToggle.setAttribute('aria-label', translations[lang][isArabic ? 'language.switchToEnglish' : 'language.switchToArabic']);
        menuToggle.setAttribute('aria-label', translations[lang][menuToggle.getAttribute('aria-expanded') === 'true' ? 'menu.close' : 'menu.open']);

        document.querySelectorAll('a[href]').forEach((link) => {
            const target = new URL(link.href, window.location.href);
            if (target.origin === window.location.origin && target.pathname.endsWith('.html')) {
                target.searchParams.set('lang', lang);
                link.href = target.href;
            }
        });

        translatedElements.forEach((element) => {
            translationAttributes.forEach(([dataKey, attribute]) => {
                const key = element.dataset[dataKey];
                if (!key || !Object.prototype.hasOwnProperty.call(translations[lang], key)) {
                    return;
                }

                const text = Object.prototype.hasOwnProperty.call(siteOverrides, key)
                    ? siteOverrides[key]
                    : translations[lang][key];
                if (attribute === 'textContent') {
                    element.textContent = text;
                } else {
                    element.setAttribute(attribute, text);
                }
            });
        });

        applyNavigationSettings();
        document.dispatchEvent(new CustomEvent('site-language-change', { detail: { lang } }));
    }

    function applyNavigationSettings() {
        const savedHiddenPages = localStorage.getItem('ourPalestineHiddenNavigation');
        if (!savedHiddenPages) {
            return;
        }

        try {
            const hiddenPages = JSON.parse(savedHiddenPages);
            if (!Array.isArray(hiddenPages)) {
                throw new Error('Saved navigation settings have an invalid format.');
            }
            navLinks.forEach((link) => {
                const page = new URL(link.href, window.location.href).pathname.split('/').pop();
                link.closest('li').hidden = hiddenPages.includes(page);
            });
        } catch (error) {
            console.error('Could not apply saved navigation settings.', error);
        }
    }

    function renderCommunityNews() {
        const newsContainer = document.getElementById('community-news');
        if (!newsContainer) {
            return;
        }
        const savedNews = localStorage.getItem('ourPalestineNews');
        if (!savedNews) {
            newsContainer.closest('section').hidden = true;
            return;
        }
        try {
            const items = JSON.parse(savedNews);
            if (!Array.isArray(items)) {
                throw new Error('Saved news data has an invalid format.');
            }
            newsContainer.replaceChildren();
            items.forEach((item) => {
                const card = document.createElement('article');
                card.className = 'card';
                const heading = document.createElement('h2');
                heading.textContent = item.title;
                const text = document.createElement('p');
                text.textContent = item.text;
                card.append(heading, text);
                newsContainer.appendChild(card);
            });
            newsContainer.closest('section').hidden = items.length === 0;
        } catch (error) {
            console.error('Could not render published community news.', error);
        }
    }

    function setMenuOpen(isOpen) {
        menu.classList.toggle('is-open', isOpen);
        menuToggle.setAttribute('aria-expanded', String(isOpen));
        menuToggle.setAttribute('aria-label', translations[currentLang][isOpen ? 'menu.close' : 'menu.open']);
    }

    menuToggle.addEventListener('click', () => {
        setMenuOpen(menuToggle.getAttribute('aria-expanded') !== 'true');
    });

    langToggle.addEventListener('click', () => {
        setLanguage(currentLang === 'en' ? 'ar' : 'en');
    });

    document.addEventListener('keydown', (event) => {
        if (event.key === 'Escape') {
            setMenuOpen(false);
        }
    });

    navLinks.forEach((link) => {
        link.addEventListener('click', () => setMenuOpen(false));
    });

    const currentPage = window.location.pathname.split('/').pop() || 'our-palistain.html';
    navLinks.forEach((link) => {
        const targetPage = new URL(link.href, window.location.href).pathname.split('/').pop();
        link.classList.toggle('active', targetPage === currentPage);
    });

    setLanguage(currentLang);
    renderCommunityNews();
}

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initializeSite, { once: true });
} else {
    initializeSite();
}
